async function deleteIncome(incomeId) {

    const confirmDelete = confirm(
        "Are you sure you want to delete this income?"
    );

    if (!confirmDelete) {
        return;
    }

    try {

        const response = await fetch(
            `http://localhost:5000/api/incomes/${incomeId}`,
            {
                method: "DELETE"
            }
        );

        const data = await response.json();

        console.log("Delete Income Response:", data);

        if (!data.success) {

            alert(
                data.message || "Failed to delete income"
            );

            return;
        }

        alert("Income deleted successfully!");

        // Refresh list
        await loadIncomeList();

    } catch (error) {

        console.error(
            "❌ Delete Income Error:",
            error
        );

        alert("Something went wrong while deleting income.");

    }

}


async function editIncome(incomeId) {

    try {

        const createdBy = 1;

        const response = await fetch(
            `http://localhost:5000/api/incomes/${createdBy}`
        );

        const data = await response.json();

        console.log("Edit Income Data:", data);

        if (!data.success) {
            alert("Failed to load income data");
            return;
        }

        const income = data.incomes.find(
            item => Number(item.income_id) === Number(incomeId)
        );

        if (!income) {
            alert("Income record not found");
            return;
        }

        // ==========================================
        // SET DATE
        // ==========================================

        document.getElementById("incomeDate").value =
            income.income_date;


        // ==========================================
        // CLEAR OLD ROWS
        // ==========================================

        const incomeItems =
            document.getElementById("incomeItems");

        incomeItems.innerHTML = "";


        // ==========================================
        // ADD EXISTING ITEMS
        // ==========================================

        income.items.forEach((item, index) => {

            const row =
                document.createElement("div");

            row.className = "income-row";

            row.innerHTML = `

                <div class="form-group">

                    <label>
                        Source
                    </label>

                    <input
                        type="text"
                        class="incomeSource"
                        value="${item.source}"
                        required
                    >

                </div>


                <div class="form-group">

                    <label>
                        Amount (₹)
                    </label>

                    <input
                        type="number"
                        class="incomeAmount"
                        value="${item.amount}"
                        min="0"
                        step="0.01"
                        required
                    >

                </div>

            `;

            incomeItems.appendChild(row);

        });


        // ==========================================
        // STORE EDIT ID
        // ==========================================

        document
            .getElementById("incomeForm")
            .dataset.editId = incomeId;


        // ==========================================
        // CHANGE BUTTON TEXT
        // ==========================================

        const saveButton =
            document.getElementById("saveIncome");

        saveButton.innerHTML = `
            <i class="fa-solid fa-pen"></i>
            Update Income
        `;


        // Scroll to form
        document
            .getElementById("incomeSection")
            .scrollIntoView({
                behavior: "smooth"
            });


    } catch (error) {

        console.error(
            "❌ Edit Income Error:",
            error
        );

    }

}

