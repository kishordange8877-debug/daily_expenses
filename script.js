async function loadExpenses(date = "") {

    try {

        let url =
            `${API_BASE_URL}/api/expenses/${CREATED_BY}`;

        // Date filter
        if (date) {
            url += `?date=${encodeURIComponent(date)}`;
        }

        console.log("Loading Expenses:", url);

        const response = await fetch(url);

        const data = await response.json();

        console.log("Expense List Response:", data);

        if (!data.success) {

            console.error(
                "Expense loading failed:",
                data.message
            );

            return;
        }

        const tableBody =
            document.getElementById("expenseTableBody");

        if (!tableBody) {

            console.error(
                "expenseTableBody not found"
            );

            return;
        }

        // Clear table
        tableBody.innerHTML = "";


        // No records
        if (
            !data.expenses ||
            data.expenses.length === 0
        ) {

            tableBody.innerHTML = `
                <tr>
                    <td colspan="5">
                        No expenses found
                    </td>
                </tr>
            `;

            return;
        }


        // ==========================================
        // CREATE TABLE ROWS
        // ==========================================

        data.expenses.forEach(function (expense) {

            const row =
                document.createElement("tr");


            // IMPORTANT:
            // Date ला Date object मध्ये convert करू नका.
            // Backend मधून आलेली YYYY-MM-DD string direct दाखवा.

            let expenseDate = expense.expense_date;

            // जर backend कडून accidentally
            // 2026-08-12T00:00:00 आले तर
            // फक्त YYYY-MM-DD घ्या.

            if (expenseDate) {
                expenseDate =
                    String(expenseDate).split("T")[0];
            }


            row.innerHTML = `

                <td>
                    ${expense.expense_id}
                </td>

                <td>
                    ${expenseDate}
                </td>

                <td>
                    ₹${Number(
                        expense.total_amount
                    ).toFixed(2)}
                </td>

                <td>
                    ${expense.created_by}
                </td>

                <td>

                    <button
                        type="button"
                        class="expense-edit-btn"
                        onclick="editExpense(${expense.expense_id})"
                    >
                        Edit
                    </button>

                    <button
                        type="button"
                        class="expense-delete-btn"
                        onclick="deleteExpense(${expense.expense_id})"
                    >
                        Delete
                    </button>

                </td>

            `;


            tableBody.appendChild(row);

        });


    } catch (error) {

        console.error(
            "Load Expenses Error:",
            error
        );

    }

}
