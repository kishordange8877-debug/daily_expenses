function setCreatedDate() {

    if (!createdDate) {
        return;
    }

    const today =
        new Date();

    const year =
        today.getFullYear();

    const month =
        String(
            today.getMonth() + 1
        ).padStart(2, "0");

    const day =
        String(
            today.getDate()
        ).padStart(2, "0");

    createdDate.value =
        `${year}-${month}-${day}`;
}


// ============================================================
// SAVE CATEGORY
// ============================================================
if (categoryForm) {

    categoryForm.addEventListener(
        "submit",
        async function (event) {

            event.preventDefault();


            // -----------------------------------------------
            // Get category name
            // -----------------------------------------------

            const name =
                categoryName.value.trim();


            // -----------------------------------------------
            // Get selected date
            // -----------------------------------------------

            const selectedDate =
                createdDate.value;


            console.log(
                "CATEGORY DATE:",
                selectedDate
            );


            // -----------------------------------------------
            // Get logged-in user ID
            // -----------------------------------------------

            const loggedInUserId =
                localStorage.getItem("loggedInUser");


            console.log(
                "CATEGORY CREATED BY:",
                loggedInUserId
            );


            // -----------------------------------------------
            // Validation
            // -----------------------------------------------

            if (!name) {

                alert(
                    "Please enter category name."
                );

                categoryName.focus();

                return;

            }


            if (!selectedDate) {

                alert(
                    "Please select created date."
                );

                createdDate.focus();

                return;

            }


            if (!loggedInUserId) {

                alert(
                    "User is not logged in. Please login again."
                );

                window.location.href =
                    "./login.html";

                return;

            }


            // -----------------------------------------------
            // Button loading
            // -----------------------------------------------

            if (saveCategoryBtn) {

                saveCategoryBtn.disabled = true;

                saveCategoryBtn.innerHTML =
                    `
                    <i class="fa-solid fa-spinner fa-spin"></i>
                    Saving...
                    `;

            }


            try {

                // -------------------------------------------
                // POST CATEGORY API
                // -------------------------------------------

                const response =
                    await fetch(
                        `${API_BASE_URL}/api/categories`,
                        {

                            method: "POST",

                            headers: {

                                "Content-Type":
                                    "application/json"

                            },

                            body: JSON.stringify({

                                category_name:
                                    name,

                                created_by:
                                    loggedInUserId,

                                created_at:
                                    selectedDate

                            })

                        }
                    );


                // -------------------------------------------
                // Read response
                // -------------------------------------------

                const responseText =
                    await response.text();


                let data = {};

                try {

                    data =
                        responseText
                            ? JSON.parse(responseText)
                            : {};

                }
                catch (jsonError) {

                    console.error(
                        "Invalid JSON response:",
                        responseText
                    );

                    alert(
                        `Server returned an invalid response. Status: ${response.status}`
                    );

                    return;

                }


                // -------------------------------------------
                // API ERROR
                // -------------------------------------------

                if (
                    !response.ok ||
                    !data.success
                ) {

                    alert(
                        data.message ||
                        `Category could not be added. Status: ${response.status}`
                    );

                    return;

                }


                // -------------------------------------------
                // SUCCESS
                // -----------------------------------------------

                alert(
                    "Category added successfully!"
                );


                // -----------------------------------------------
                // Clear category name
                // -----------------------------------------------

                categoryName.value = "";


                // -----------------------------------------------
                // Refresh category list
                // -----------------------------------------------

                await loadCategories();

            }


            catch (error) {

                console.error(
                    "Category Save Error:",
                    error
                );

                alert(
                    "Server connection failed. Make sure your backend is running on port 5000."
                );

            }


            finally {

                // -----------------------------------------------
                // Button normal
                // -----------------------------------------------

                if (saveCategoryBtn) {

                    saveCategoryBtn.disabled = false;

                    saveCategoryBtn.innerHTML =
                        `
                        <i class="fa-solid fa-plus"></i>
                        Save Category
                        `;

                }

            }

        }
    );

}

// ============================================================
// GET CATEGORIES
// ============================================================

async function loadCategories() {

       console.log(
        "🔥 LOAD CATEGORIES CALLED"
    );



    if (!categoryTableBody) {

        return;

    }


    try {

        // -----------------------------------------------
        // Loading
        // -----------------------------------------------

        categoryTableBody.innerHTML =
            `
            <tr>

                <td
                    colspan="5"
                    style="text-align:center;"
                >

                    Loading categories...

                </td>

            </tr>
            `;


        // -----------------------------------------------
        // GET API
        // -----------------------------------------------

        const response =
            await fetch(
                `${API_BASE_URL}/api/categories/${CREATED_BY}`
            );
           
 

console.log(
    "CATEGORY API URL:",
    `${API_BASE_URL}/api/categories/${CREATED_BY}`
);

console.log(
    "CATEGORY API STATUS:",
    response.status
);


        // -----------------------------------------------
        // Safe response
        // -----------------------------------------------

        const responseText =
            await response.text();


        let data = {};

        try {

            data =
                responseText
                    ? JSON.parse(responseText)
                    : {};

        } catch (jsonError) {

            console.error(
                "Invalid GET response:",
                responseText
            );

            throw new Error(
                `Invalid server response. Status: ${response.status}`
            );

        }


        // -----------------------------------------------
        // API ERROR
        // -----------------------------------------------

        if (
            !response.ok ||
            !data.success
        ) {

            throw new Error(
                data.message ||
                "Unable to load categories."
            );

        }


        // -----------------------------------------------
        // Display
        // -----------------------------------------------

        displayCategories(
            data.categories || []
        );

    }


    catch (error) {

        console.error(
            "Load Categories Error:",
            error
        );


        categoryTableBody.innerHTML =
            `
            <tr>

                <td
                    colspan="5"
                    style="
                        text-align:center;
                        color:#ee5d50;
                    "
                >

                    Failed to load categories.

                </td>

            </tr>
            `;


        if (categoryMobileList) {

            categoryMobileList.innerHTML =
                `
                <div
                    style="
                        text-align:center;
                        padding:25px;
                        color:#ee5d50;
                    "
                >

                    Failed to load categories.

                </div>
                `;

        }

    }

}


