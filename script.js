async function loadDashboardSummary() {

    try {

        if (!CREATED_BY) {

            console.error(
                "CREATED_BY is missing"
            );

            return;

        }


        // ---------------------------------------------
        // GET DATE
        // ---------------------------------------------

        const date =
            selectedDate
                ? selectedDate.value
                : "";


        // ---------------------------------------------
        // GET PERIOD
        // ---------------------------------------------

        const filter =
            dashboardPeriod
                ? dashboardPeriod.value
                : "";


        // ---------------------------------------------
        // API URL
        // ---------------------------------------------

        let url =
            `${API_BASE_URL}/api/dashboard/summary/${encodeURIComponent(CREATED_BY)}`;


        const params =
            new URLSearchParams();


        if (date) {

            params.append(
                "date",
                date
            );

        }


        if (filter) {

            params.append(
                "filter",
                filter
            );

        }


        if (params.toString()) {

            url += `?${params.toString()}`;

        }


        console.log(
            "DASHBOARD URL:",
            url
        );


        // ---------------------------------------------
        // API CALL
        // ---------------------------------------------

        const response =
            await fetch(url);


        const data =
            await response.json();


        console.log(
            "DASHBOARD RESPONSE:",
            data
        );


        // ---------------------------------------------
        // ERROR
        // ---------------------------------------------

        if (
            !response.ok ||
            !data.success
        ) {

            console.error(
                "Dashboard API Error:",
                data
            );

            return;

        }


        // ---------------------------------------------
        // GET VALUES
        // ---------------------------------------------

        const totalIncome =
            Number(
                data.summary.total_income || 0
            );


        const totalExpense =
            Number(
                data.summary.total_expense || 0
            );


        const profit =
            Number(
                data.summary.net_profit || 0
            );


        // ---------------------------------------------
        // UPDATE TOTAL INCOME
        // ---------------------------------------------

        const incomeElement =
            document.getElementById(
                "totalIncome"
            );


        if (incomeElement) {

            incomeElement.textContent =
                `₹ ${totalIncome.toFixed(2)}`;

        }


        // ---------------------------------------------
        // UPDATE TOTAL EXPENSE
        // ---------------------------------------------

        const expenseElement =
            document.getElementById(
                "totalExpense"
            );


        if (expenseElement) {

            expenseElement.textContent =
                `₹ ${totalExpense.toFixed(2)}`;

        }


        // ---------------------------------------------
        // UPDATE PROFIT
        // ---------------------------------------------

        const profitElement =
            document.getElementById(
                "profit"
            );


        if (profitElement) {

            profitElement.textContent =
                `₹ ${profit.toFixed(2)}`;

        }


        // ---------------------------------------------
        // UPDATE DASHBOARD TEXT
        // ---------------------------------------------

        const displayDate =
            document.getElementById(
                "displayDate"
            );


        if (displayDate) {

            if (!date && !filter) {

                displayDate.textContent =
                    "Previous Day";

            }

            else if (filter === "day") {

                displayDate.textContent =
                    `One Day - ${date}`;

            }

            else if (filter === "week") {

                displayDate.textContent =
                    `One Week - ${date}`;

            }

            else if (filter === "month") {

                displayDate.textContent =
                    `One Month - ${date}`;

            }

            else if (filter === "year") {

                displayDate.textContent =
                    `One Year - ${date}`;

            }

            else {

                displayDate.textContent =
                    `Date - ${date}`;

            }

        }


    } catch (error) {

        console.error(
            "❌ Dashboard Summary Error:",
            error
        );

    }

}

