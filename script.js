function initializeDashboard() {

    console.log(
        "Initializing Dashboard..."
    );


    // Date खाली ठेवायची
    const selectedDate =
        document.getElementById(
            "selectedDate"
        );


    // Period Previous Day ठेवायचा
    const dashboardPeriod =
        document.getElementById(
            "dashboardPeriod"
        );


    if (selectedDate) {

        selectedDate.value = "";

    }


    if (dashboardPeriod) {

        dashboardPeriod.value = "";

    }


    // Previous Day data load करा

    loadDashboardSummary();

}


